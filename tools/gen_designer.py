# -*- coding: utf-8 -*-
"""
สร้างไฟล์ *.designer.cs จาก .aspx/.Master (ประกาศฟิลด์ของคอนโทรลที่มี runat="server")
Visual Studio สร้างให้อัตโนมัติเมื่อเปิดโปรเจกต์/บันทึกไฟล์ .aspx อยู่แล้ว สคริปต์นี้มีไว้ให้ build ได้โดยไม่ต้องเปิด VS
ใช้งาน:  python tools/gen_designer.py "Cinema Ticketing & Seat Booking"
"""
import os, re, sys

TEMPLATE_BLOCKS = ["ItemTemplate", "AlternatingItemTemplate", "HeaderTemplate", "FooterTemplate", "SeparatorTemplate",
                   "EditItemTemplate", "EmptyDataTemplate", "Columns", "LayoutTemplate"]
HTML_TAGS = {"form": "System.Web.UI.HtmlControls.HtmlForm", "head": "System.Web.UI.HtmlControls.HtmlHead",
             "div": "System.Web.UI.HtmlControls.HtmlGenericControl", "span": "System.Web.UI.HtmlControls.HtmlGenericControl",
             "input": "System.Web.UI.HtmlControls.HtmlInputText", "a": "System.Web.UI.HtmlControls.HtmlAnchor"}

def fields_for(text):
    for t in TEMPLATE_BLOCKS:
        text = re.sub(r"<asp:%s\b[^>]*>.*?</asp:%s>" % (t, t), "", text, flags=re.S)
        text = re.sub(r"<%s>.*?</%s>" % (t, t), "", text, flags=re.S)
    out = []
    for m in re.finditer(r"<(asp:\w+|form|head|div|span|input|a)\b([^>]*?)>", text, re.S | re.I):
        tag, attrs = m.group(1), m.group(2)
        if not re.search(r'runat\s*=\s*"server"', attrs, re.I): continue
        idm = re.search(r'\bID\s*=\s*"([^"]+)"', attrs, re.I) or re.search(r'\bid\s*=\s*"([^"]+)"', attrs)
        if not idm: continue
        if tag.lower() == "asp:content": continue
        typ = "System.Web.UI.WebControls." + tag.split(":")[1] if tag.lower().startswith("asp:") else HTML_TAGS[tag.lower()]
        out.append((idm.group(1), typ))
    return out

def process(path):
    text = open(path, encoding="utf-8-sig").read()
    inh = re.search(r'Inherits="([^"]+)"', text)
    if not inh: return None
    full = inh.group(1); ns, cls = full.rsplit(".", 1)
    flds = fields_for(text)
    body = "\n\n".join("        protected global::%s %s;" % (t, i) for i, t in flds)
    code = ("//------------------------------------------------------------------------------\n// <auto-generated>\n//     สร้างโดย tools/gen_designer.py (Visual Studio จะสร้างทับให้อัตโนมัติเมื่อแก้ไฟล์ .aspx)\n// </auto-generated>\n"
            "//------------------------------------------------------------------------------\n\nnamespace %s\n{\n    public partial class %s\n    {\n%s\n    }\n}\n" % (ns, cls, body))
    dest = path + ".designer.cs"
    open(dest, "w", encoding="utf-8-sig").write(code)
    return dest, len(flds)

if __name__ == "__main__":
    root = sys.argv[1]
    for d, _, files in os.walk(root):
        if any(x in d for x in ("/bin", "/obj", "/.vs")): continue
        for f in files:
            if f.endswith((".aspx", ".Master")):
                r = process(os.path.join(d, f))
                if r: print("designer:", os.path.relpath(r[0], root), r[1], "fields")
